package knx_test

import (
	"context"
	"fmt"
	"time"

	"github.com/cB-Sigma/knx"
	knxsim "github.com/cB-Sigma/knx-sim/sim"
)

// Tunnel to a gateway (here the simulator), switch a light and read a
// temperature.
func Example() {
	gw, _ := knxsim.Start()
	defer gw.Close()
	temp, _ := knx.ParseGroupAddress("1/2/3")
	light, _ := knx.ParseGroupAddress("1/1/7")
	celsius, _ := knx.ParseDPT("9.001")
	v, _ := celsius.Encode(21.5)
	gw.Set(temp, v)

	answers := make(chan any, 1)
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	tn, err := knx.DialTunnel(ctx, gw.Addr(), knx.TunnelOptions{OnFrame: func(f knx.LData) {
		if f.APCI == knx.GroupValueResponse && f.Group() == temp {
			v, _ := celsius.Decode(f.Value())
			answers <- v
		}
	}})
	if err != nil {
		fmt.Println(err)
		return
	}
	defer tn.Close()

	_ = tn.Send(ctx, knx.GroupFrame(knx.LDataReq, light, knx.GroupValueWrite, []byte{1}, true))
	fmt.Println("light:", gw.Get(light))
	_ = tn.Send(ctx, knx.GroupFrame(knx.LDataReq, temp, knx.GroupValueRead, nil, true))
	fmt.Println("temperature:", <-answers, celsius.Unit())
	// Output:
	// light: [1]
	// temperature: 21.5 Cel
}

// Read a password-protected ETS 6 project export and a keyring, both
// generated by the simulator.
func Example_etsProject() {
	export := knxsim.ETSProject(knxsim.ETSProjectOptions{Name: "Home", Password: "secret", ETS6: true,
		Ranges: []knxsim.ETSRange{{Name: "Kitchen", Groups: []knxsim.ETSGroup{{Address: "1/1/1", Name: "Ceiling light", DPT: "DPST-1-1"}}}}})
	p, err := knx.ParseETSProject(export, "secret")
	if err != nil {
		fmt.Println(err)
		return
	}
	pts, _ := knx.ETSPoints(p, nil, "home")
	for _, pt := range pts {
		fmt.Println(pt.Device, pt.Name, pt.GroupAddress, pt.DPT, pt.Writable)
	}

	keys := knxsim.ETSKeyring(knxsim.KeyringOptions{Project: "Home", Password: "keyring-pass", Host: "1.1.250",
		DeviceAuth: "gateway-auth", Tunnels: []knxsim.KeyringTunnel{{Address: "1.1.251", UserID: 2, Password: "tunnel-pass"}}})
	k, _ := knx.ParseKeyring(keys, "keyring-pass")
	in, auth, _ := k.Tunnel("", 0)
	fmt.Println(in.IndividualAddress, in.UserID, in.Password, auth)
	// Output:
	// kitchen ceiling-light 1/1/1 1.001 true
	// 1.1.251 2 tunnel-pass gateway-auth
}
